// Generates src/drawing/fonts/tinos-metrics.ts (advance widths per code point) from the
// Tinos TTFs, so sheet functions can measure text without a DOM. Run: yarn gen:font-metrics
import { writeFileSync } from 'node:fs'
import { openSync } from 'fontkit'
import type { Font } from 'fontkit'

const STYLES = {
  regular: 'Tinos-Regular.ttf',
  bold: 'Tinos-Bold.ttf',
  italic: 'Tinos-Italic.ttf',
  boldItalic: 'Tinos-BoldItalic.ttf',
} as const

/** Basic Latin, Latin-1, Latin Extended-A/B, combining marks, Vietnamese precomposed, punctuation. */
const RANGES: Array<[number, number]> = [
  [0x20, 0x7e],
  [0xa0, 0x24f],
  [0x300, 0x323],
  [0x1ea0, 0x1ef9],
  [0x2010, 0x2026],
  [0x2030, 0x203a],
  [0x20ab, 0x20ac],
  [0x2116, 0x2116],
  [0x2212, 0x2212],
]

const dir = new URL('../public/fonts/tinos/', import.meta.url)

function widths(font: Font): Record<number, number> {
  const out: Record<number, number> = {}
  for (const [from, to] of RANGES) {
    for (let cp = from; cp <= to; cp++) {
      if (!font.hasGlyphForCodePoint(cp)) continue
      out[cp] = font.glyphForCodePoint(cp).advanceWidth
    }
  }
  return out
}

const fonts = Object.fromEntries(
  Object.entries(STYLES).map(([style, file]) => [
    style,
    openSync(new URL(file, dir).pathname) as Font,
  ]),
) as Record<keyof typeof STYLES, Font>

const unitsPerEm = fonts.regular.unitsPerEm
const lines = [
  '// Generated by scripts/gen-font-metrics.ts from public/fonts/tinos/*.ttf — do not edit.',
  `export const UNITS_PER_EM = ${unitsPerEm}`,
  `/** Ascender / descender of Tinos Regular, in font units. */`,
  `export const ASCENT = ${fonts.regular.ascent}`,
  `export const DESCENT = ${fonts.regular.descent}`,
  '',
  '/** Advance width (font units) by code point, per style. */',
  'export const ADVANCE: Record<',
  "  'regular' | 'bold' | 'italic' | 'boldItalic',",
  '  Record<number, number>',
  '> = {',
]
for (const [style, font] of Object.entries(fonts)) {
  if (font.unitsPerEm !== unitsPerEm)
    throw new Error(`${style}: unitsPerEm differs`)
  const w = widths(font)
  lines.push(`  ${style}: ${JSON.stringify(w).replace(/"/g, '')},`)
}
lines.push('}', '')

const target = new URL('../src/drawing/fonts/tinos-metrics.ts', import.meta.url)
writeFileSync(target, lines.join('\n'))
console.log(`Wrote ${target.pathname}`)
